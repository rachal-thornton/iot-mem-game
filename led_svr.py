#!/usr/bin/python3

# Imports
import socket
import sys
import os
import time
from gpiozero import LED
# Import game logic from led_memory_game.py
import led_memory_game

# Assign server host and port
HOST = '199.17.161.147' # Listening IP
PORT = 3147             # Listening port

# Assign led lights to GPIO pins
r_led = LED(20)  # Red led; change GPIO pin as needed
g_led = LED(21)  # Green led; change GPIO pin as needed
y_led = LED(16)  # Yellow led; change GPIO pin as needed

# Create socket
s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
print('Socket created')

# Bind host and port
try:
    s.bind((HOST, PORT))
except socket.error:
    print('Bind failed.')
    sys.exit()

# Socket listening
print('Socket bind complete')
s.listen(10)
print('Socket now listening')

# light_up: Function to light up a specific led color with a clear on/off rhythm
# Pre: Color chosen
# Post: Specified led lights up for 1 second, then stays off longer
def light_up(color):
    on_time = 1.0
    off_time = 0.8

    if color == "red":
        r_led.on()
        time.sleep(on_time)
        r_led.off()
    elif color == "green":
        g_led.on()
        time.sleep(on_time)
        g_led.off()
    elif color == "yellow":
        y_led.on()
        time.sleep(on_time)
        y_led.off()

    time.sleep(off_time)

# Main server logic
while True:
    conn, addr = s.accept()
    print('Connected with ' + addr[0] + ':' + str(addr[1]))

    game = None  # Game state starts as none
    reply = ""   # Reply initialized

    while True:  # Loop to handle multiple messages per connection
        data = conn.recv(1024)
        if not data:
            break

        # Decode client message
        message = data.decode("utf-8").strip().lower()
        print("Client said:", message)

        # Server responds with game logic
        # User wants to play
        if message == "play":
            game = led_memory_game.MemGame()    # Initialize a memory game
            game.generate_sequence()    # Generate a random sequence of lights

            # Light up sequence generated by server
            for color in game.sequence:
                light_up(color)

            # Prompt for user guess
            reply = "Sequence shown. Input your guess as a comma seperated list of colors (ex. 'red, green, yellow'):" + os.linesep
        
        elif message.startswith("sequence:"):
            # Check if game has started
            if game is None:
                reply = "Please start a game first by typing 'play'." + os.linesep
            else:
                # Process user guess and check against correct sequence
                seq_str = message[9:].strip()  # Remove "sequence:" prefix
                guess = [color.strip() for color in seq_str.split(",")]
                for color in guess:
                    game.add_client_input(color)

                if game.check_client_sequence():
                    reply = "Correct! You win!" + os.linesep
                else:
                    reply = "Incorrect! The sequence was: " + ", ".join(game.sequence) + os.linesep
                    game.reset_game()
        
        # Check if user wants to quit
        elif message == "quit":
            reply = "Goodbye!" + os.linesep
            conn.sendall(reply.encode("utf-8"))
            break  # End this connection
        
        else:
            reply = "Unknown command" + os.linesep

        if reply:  # Send reply if set
            conn.sendall(reply.encode("utf-8"))
            reply = ""  # Reset

    conn.close()